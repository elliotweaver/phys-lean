from fractions import Fraction as F
# base decomposition identities (Lean-checkable by norm_num)
print("6923/54 + 128/27 + 16/9 =", F(6923,54)+F(128,27)+F(16,9), "  (2425/18 =", F(2425,18), ")")
print("6923/54 + 128/27 + 40/27 =", F(6923,54)+F(128,27)+F(40,27), "  (7259/54 =", F(7259,54), ")")
print("2425/18 - 7259/54 =", F(2425,18)-F(7259,54), "  (8/27 =", F(8,27), ")")
print("16/9 - 40/27 =", F(16,9)-F(40,27), "  (8/27 =", F(8,27), ")")
print("7179/54 = 6923/54 + 128/27 :", F(7179,54)==F(6923,54)+F(128,27))
print("2425/18 = 7179/54 + 16/9 :", F(2425,18)==F(7179,54)+F(16,9))
print("128/27 = kappa*(16/3)*(8pi/3) with kappa=1/(3pi): 16/3*8/9 =", F(16,3)*F(8,9))
print("16/9   = kappa*2*(8pi/3): 2*8/9 =", F(2)*F(8,9))
print("40/27  = kappa*(5/3)*(8pi/3): 5/3*8/9 =", F(5,3)*F(8,9))
