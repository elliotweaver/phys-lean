"""artin (run 50): per zero-diagonal-core entry, which of the 6 generators appear, and
how many DISTINCT base generators each monomial mixes. Artin's theorem: the subalgebra
generated by <=2 elements of an alternative algebra is associative. If any core entry's
monomials each involve <=2 distinct generators, those associate freely (alt laws give
full associativity on 2-generated) and may close more cheaply. Diagnostic only."""
from fractions import Fraction as F
from collections import defaultdict
GEN=['a','b','c','p','q','r']
STAR={'a':'A','b':'B','c':'C','p':'P','q':'Q','r':'R'}
for k,v in list(STAR.items()): STAR[v]=k
def is_leaf(m): return isinstance(m,str)
def add(*xs):
    r=defaultdict(F)
    for x in xs:
        for m,v in x.items(): r[m]+=v
    return {m:v for m,v in r.items() if v!=0}
def neg(x): return {m:-v for m,v in x.items()}
def mul(x,y):
    r=defaultdict(F)
    for mx,cx in x.items():
        for my,cy in y.items(): r[(mx,my)]+=cx*cy
    return {m:v for m,v in r.items() if v!=0}
def E(m): return {m:F(1)}
ZERO={}
def mz(n): return [[dict(ZERO) for _ in range(n)] for _ in range(n)]
def madd(A,B): n=len(A); return [[add(A[i][j],B[i][j]) for j in range(n)] for i in range(n)]
def mmul(A,B):
    n=len(A); C=mz(n)
    for i in range(n):
        for j in range(n):
            s=dict(ZERO)
            for k in range(n): s=add(s,mul(A[i][k],B[k][j]))
            C[i][j]=s
    return C
def mneg(A): return [[neg(x) for x in row] for row in A]
def jb(A,B): return madd(mmul(A,B),mmul(B,A))
def jdef(A,B):
    AA=jb(A,A); return madd(jb(jb(A,B),AA), mneg(jb(A,jb(B,AA))))
def Xz(off):
    a,b,c=off
    return [[dict(ZERO),E(a),E(b)],[E(STAR[a]),dict(ZERO),E(c)],[E(STAR[b]),E(STAR[c]),dict(ZERO)]]
X=Xz(('a','b','c')); Y=Xz(('p','q','r'))
D=jdef(X,Y)
def leaves(m,acc):
    if is_leaf(m): acc.append(m)
    else: leaves(m[0],acc); leaves(m[1],acc)
def base(l): return l.lower()
for (i,j) in [(0,0),(1,1),(2,2),(0,1),(0,2),(1,2)]:
    E_=D[i][j]; bases=set()
    for m in E_:
        acc=[]; leaves(m,acc)
        for l in acc: bases.add(base(l))
    print(f"core ({i},{j}): {len(E_)} monomials, distinct base generators {sorted(bases)} (count {len(bases)})")
print("---- per-monomial distinct-base distribution ----")
for (i,j) in [(0,0),(0,1)]:
    E_=D[i][j]; hist=defaultdict(int)
    for m in E_:
        acc=[]; leaves(m,acc); hist[len(set(base(l) for l in acc))]+=1
    print(f"core ({i},{j}): #distinct-bases-per-monomial histogram {dict(sorted(hist.items()))}")
